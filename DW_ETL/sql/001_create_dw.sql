BEGIN;
CREATE SCHEMA IF NOT EXISTS dw;
SET search_path TO dw, public;

CREATE TABLE IF NOT EXISTS dim_date (
    date_key DATE PRIMARY KEY,
    year SMALLINT NOT NULL,
    quarter SMALLINT NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    month SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),
    month_name VARCHAR(12) NOT NULL,
    day_of_month SMALLINT NOT NULL CHECK (day_of_month BETWEEN 1 AND 31),
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    day_name VARCHAR(12) NOT NULL,
    is_weekend BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS dim_seller (
    seller_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id VARCHAR(64) NOT NULL UNIQUE,
    seller_zip_code_prefix VARCHAR(16),
    seller_city VARCHAR(120),
    seller_state VARCHAR(8)
);

CREATE TABLE IF NOT EXISTS dim_product (
    product_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id VARCHAR(64) NOT NULL UNIQUE,
    product_category_name VARCHAR(120),
    product_category_name_english VARCHAR(120),
    product_name_length INTEGER,
    product_description_length INTEGER,
    product_photos_qty INTEGER,
    product_weight_g NUMERIC(12,3),
    product_length_cm NUMERIC(12,3),
    product_height_cm NUMERIC(12,3),
    product_width_cm NUMERIC(12,3)
);

CREATE TABLE IF NOT EXISTS dim_customer (
    customer_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(64) NOT NULL UNIQUE,
    customer_unique_id VARCHAR(64),
    customer_zip_code_prefix VARCHAR(16),
    customer_city VARCHAR(120),
    customer_state VARCHAR(8)
);

CREATE TABLE IF NOT EXISTS dim_order_status (
    order_status_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_status VARCHAR(32) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS fact_sales_item (
    sales_item_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(64) NOT NULL,
    order_item_id INTEGER NOT NULL CHECK (order_item_id > 0),
    seller_key BIGINT NOT NULL REFERENCES dim_seller(seller_key),
    product_key BIGINT NOT NULL REFERENCES dim_product(product_key),
    purchase_date_key DATE REFERENCES dim_date(date_key),
    price NUMERIC(14,2) NOT NULL CHECK (price >= 0),
    freight_value NUMERIC(14,2) NOT NULL CHECK (freight_value >= 0),
    item_count SMALLINT NOT NULL DEFAULT 1 CHECK (item_count = 1),
    order_status_key BIGINT NOT NULL REFERENCES dim_order_status(order_status_key),
    CONSTRAINT uq_fact_sales_item_business_key UNIQUE (order_id, order_item_id)
);

CREATE TABLE IF NOT EXISTS fact_delivery_order (
    delivery_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(64) NOT NULL UNIQUE,
    customer_key BIGINT NOT NULL REFERENCES dim_customer(customer_key),
    purchase_date_key DATE REFERENCES dim_date(date_key),
    estimated_delivery_date_key DATE REFERENCES dim_date(date_key),
    actual_delivery_date_key DATE REFERENCES dim_date(date_key),
    order_status_key BIGINT NOT NULL REFERENCES dim_order_status(order_status_key),
    order_purchase_timestamp TIMESTAMP,
    order_estimated_delivery_date TIMESTAMP,
    order_delivered_customer_date TIMESTAMP,
    delivery_days INTEGER,
    delay_days INTEGER,
    is_delayed BOOLEAN,
    is_delivery_eligible BOOLEAN NOT NULL,
    CONSTRAINT ck_delivery_days_nonnegative CHECK (delivery_days IS NULL OR delivery_days >= 0),
    CONSTRAINT ck_delay_flag_consistency CHECK (
        (is_delivery_eligible = FALSE AND is_delayed IS NULL AND delay_days IS NULL)
        OR is_delivery_eligible = TRUE
    )
);

CREATE TABLE IF NOT EXISTS fact_review (
    review_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id VARCHAR(64),
    order_id VARCHAR(64) NOT NULL,
    review_creation_date_key DATE REFERENCES dim_date(date_key),
    review_score SMALLINT NOT NULL CHECK (review_score BETWEEN 1 AND 5),
    review_comment_title TEXT,
    review_comment_message TEXT,
    review_answer_timestamp TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_fact_sales_item_seller ON fact_sales_item(seller_key);
CREATE INDEX IF NOT EXISTS ix_fact_sales_item_product ON fact_sales_item(product_key);
CREATE INDEX IF NOT EXISTS ix_fact_sales_item_purchase_date ON fact_sales_item(purchase_date_key);
CREATE INDEX IF NOT EXISTS ix_fact_sales_item_status ON fact_sales_item(order_status_key);
CREATE INDEX IF NOT EXISTS ix_fact_delivery_customer ON fact_delivery_order(customer_key);
CREATE INDEX IF NOT EXISTS ix_fact_delivery_purchase_date ON fact_delivery_order(purchase_date_key);
CREATE INDEX IF NOT EXISTS ix_fact_delivery_estimated_date ON fact_delivery_order(estimated_delivery_date_key);
CREATE INDEX IF NOT EXISTS ix_fact_delivery_actual_date ON fact_delivery_order(actual_delivery_date_key);
CREATE INDEX IF NOT EXISTS ix_fact_delivery_status ON fact_delivery_order(order_status_key);
CREATE INDEX IF NOT EXISTS ix_fact_review_order ON fact_review(order_id);
CREATE INDEX IF NOT EXISTS ix_fact_review_creation_date ON fact_review(review_creation_date_key);
COMMIT;
